    "        )\n",
    "\n",
    "        SELECT\n",
    "            *,\n",
    "\n",
    "            (n_blocks_received_10d > 0)::INTEGER AS has_block_10d,\n",
    "            LN(1 + n_blocks_received_10d) AS log1p_blocks_received_10d,\n",
    "            LN(1 + n_unique_blockers_10d) AS log1p_unique_blockers_10d,\n",
    "\n",
    "            (n_blocks_day_0 > 0)::INTEGER AS has_block_day_0,\n",
    "            (n_blocks_day_1 > 0)::INTEGER AS has_block_day_1,\n",
    "            (n_blocks_day_2 > 0)::INTEGER AS has_block_day_2,\n",
    "            (n_blocks_day_3 > 0)::INTEGER AS has_block_day_3,\n",
    "            (n_blocks_day_4 > 0)::INTEGER AS has_block_day_4,\n",
    "            (n_blocks_day_5 > 0)::INTEGER AS has_block_day_5,\n",
    "            (n_blocks_day_6 > 0)::INTEGER AS has_block_day_6,\n",
    "            (n_blocks_day_7 > 0)::INTEGER AS has_block_day_7,\n",
    "            (n_blocks_day_8 > 0)::INTEGER AS has_block_day_8,\n",
    "            (n_blocks_day_9 > 0)::INTEGER AS has_block_day_9\n",
    "\n",
    "        FROM agg\n",
    "    )\n",
    "    TO '{out_path}'\n",
    "    (FORMAT PARQUET)\n",
    "    \"\"\"\n",
    "\n",
    "    con.execute(query)\n",
    "\n",
