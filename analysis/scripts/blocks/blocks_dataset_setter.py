    "def build_blocks_analysis(index_path: str, out_path: Path, label: str):\n",
    "    print(f\"\\n=== Building blocks analysis file: {label} ===\")\n",
    "\n",
    "    query = f\"\"\"\n",
    "    COPY (\n",
    "        WITH idx AS (\n",
    "            SELECT\n",
    "                did,\n",
    "                target,\n",
    "                event_time,\n",
    "                CAST(event_time AS DATE) AS event_day,\n",
    "                window_start,\n",
    "                window_end,\n",
    "                n_posts_10d,\n",
    "                incoming_follows_from_march_start,\n",
    "                post_bucket_index,\n",
    "                follow_bucket_index,\n",
    "                exposure_bucket_index\n",
    "            FROM read_parquet('{index_path}')\n",
    "        ),\n",
    "\n",
    "        blocks_filtered AS (\n",
    "            SELECT\n",
    "                {BLOCKER_COL} AS blocker_did,\n",
    "                {BLOCKED_COL} AS blocked_did,\n",
    "                {BLOCK_TIME_COL} AS block_time\n",
    "            FROM read_parquet('{BLOCKS}')\n",
    "            WHERE {BLOCK_TIME_COL} >= TIMESTAMP '2026-03-01'\n",
    "              AND {BLOCK_TIME_COL} <  TIMESTAMP '2026-03-22'\n",
    "        ),\n",
    "\n",
    "        joined AS (\n",
    "            SELECT\n",
    "                idx.did,\n",
    "                idx.target,\n",
    "                idx.event_time,\n",
    "                idx.event_day,\n",
    "                idx.window_start,\n",
    "                idx.window_end,\n",
    "                idx.n_posts_10d,\n",
    "                idx.incoming_follows_from_march_start,\n",
    "                idx.post_bucket_index,\n",
    "                idx.follow_bucket_index,\n",
    "                idx.exposure_bucket_index,\n",
    "\n",
    "                b.blocker_did,\n",
    "                b.block_time,\n",
    "\n",
    "                CASE\n",
    "                    WHEN b.block_time IS NULL THEN NULL\n",
    "                    ELSE CAST(FLOOR(EXTRACT(EPOCH FROM (idx.event_time - b.block_time)) / 86400) AS INTEGER)\n",
    "                END AS days_before_event\n",
    "\n",
    "            FROM idx\n",
    "            LEFT JOIN blocks_filtered b\n",
    "                ON b.blocked_did = idx.did\n",
    "               AND b.block_time >= idx.window_start\n",
    "               AND b.block_time <  idx.window_end\n",
    "        ),\n",
    "\n",
    "        agg AS (\n",
    "            SELECT\n",
    "                did,\n",
    "                target,\n",
    "                event_time,\n",
    "                event_day,\n",
    "                window_start,\n",
    "                window_end,\n",
    "                n_posts_10d,\n",
    "                incoming_follows_from_march_start,\n",
    "                post_bucket_index,\n",
    "                follow_bucket_index,\n",
    "                exposure_bucket_index,\n",
    "\n",
    "                COUNT(block_time) AS n_blocks_received_10d,\n",
    "                COUNT(DISTINCT blocker_did) AS n_unique_blockers_10d,\n",
    "\n",
    "                COUNT(*) FILTER (\n",
    "                    WHERE block_time >= event_time - INTERVAL 1 DAY\n",
    "                      AND block_time <  event_time\n",
    "                ) AS n_blocks_0_1d,\n",
    "\n",
    "                COUNT(*) FILTER (\n",
    "                    WHERE block_time >= event_time - INTERVAL 3 DAY\n",
    "                      AND block_time <  event_time - INTERVAL 1 DAY\n",
    "                ) AS n_blocks_1_3d,\n",
    "\n",
    "                COUNT(*) FILTER (\n",
    "                    WHERE block_time >= event_time - INTERVAL 7 DAY\n",
    "                      AND block_time <  event_time - INTERVAL 3 DAY\n",
    "                ) AS n_blocks_3_7d,\n",
    "\n",
    "                COUNT(*) FILTER (\n",
    "                    WHERE block_time >= event_time - INTERVAL 10 DAY\n",
    "                      AND block_time <  event_time - INTERVAL 7 DAY\n",
    "                ) AS n_blocks_7_10d,\n",
    "\n",
    "                -- Daily block counts: day_0 = ultimo giorno prima dell'evento\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 0) AS n_blocks_day_0,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 1) AS n_blocks_day_1,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 2) AS n_blocks_day_2,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 3) AS n_blocks_day_3,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 4) AS n_blocks_day_4,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 5) AS n_blocks_day_5,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 6) AS n_blocks_day_6,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 7) AS n_blocks_day_7,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 8) AS n_blocks_day_8,\n",
    "                COUNT(*) FILTER (WHERE days_before_event = 9) AS n_blocks_day_9,\n",
    "\n",
    "                -- Daily unique blockers\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 0) AS n_unique_blockers_day_0,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 1) AS n_unique_blockers_day_1,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 2) AS n_unique_blockers_day_2,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 3) AS n_unique_blockers_day_3,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 4) AS n_unique_blockers_day_4,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 5) AS n_unique_blockers_day_5,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 6) AS n_unique_blockers_day_6,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 7) AS n_unique_blockers_day_7,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 8) AS n_unique_blockers_day_8,\n",
    "                COUNT(DISTINCT blocker_did) FILTER (WHERE days_before_event = 9) AS n_unique_blockers_day_9\n",
    "\n",
    "            FROM joined\n",
    "            GROUP BY\n",
    "                did,\n",
    "                target,\n",
    "                event_time,\n",
    "                event_day,\n",
    "                window_start,\n",
    "                window_end,\n",
    "                n_posts_10d,\n",
    "                incoming_follows_from_march_start,\n",
    "                post_bucket_index,\n",
    "                follow_bucket_index,\n",
