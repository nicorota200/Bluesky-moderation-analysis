    "# TEXT SUMMARY PER TARGET\n",
    "# =========================\n",
    "\n",
    "def write_text_summary(path: Path, out_txt: Path, label: str):\n",
    "    general = con.execute(f\"\"\"\n",
    "        SELECT\n",
    "            COUNT(*) AS n_obs,\n",
    "            COUNT(DISTINCT did) AS n_dids,\n",
    "            SUM(n_blocks_received_10d) AS total_blocks_received_10d,\n",
    "            SUM(has_block_10d) AS n_obs_with_blocks,\n",
    "            AVG(has_block_10d) AS share_with_blocks,\n",
    "\n",
    "            AVG(n_blocks_received_10d) AS avg_blocks,\n",
    "            MEDIAN(n_blocks_received_10d) AS median_blocks,\n",
    "            QUANTILE_CONT(n_blocks_received_10d, 0.75) AS p75_blocks,\n",
    "            QUANTILE_CONT(n_blocks_received_10d, 0.90) AS p90_blocks,\n",
    "            QUANTILE_CONT(n_blocks_received_10d, 0.95) AS p95_blocks,\n",
    "            QUANTILE_CONT(n_blocks_received_10d, 0.99) AS p99_blocks,\n",
    "            MAX(n_blocks_received_10d) AS max_blocks,\n",
    "\n",
    "            AVG(n_unique_blockers_10d) AS avg_unique_blockers,\n",
    "            MAX(n_unique_blockers_10d) AS max_unique_blockers\n",
    "        FROM read_parquet('{path}')\n",
    "    \"\"\").df()\n",
    "\n",
    "    thresholds = con.execute(f\"\"\"\n",
    "        WITH thresholds(threshold) AS (\n",
    "            VALUES (1), (2), (5), (10), (25), (50), (100)\n",
    "        )\n",
    "        SELECT\n",
    "            threshold,\n",
    "            AVG((n_blocks_received_10d >= threshold)::INTEGER) AS share_above_threshold\n",
    "        FROM read_parquet('{path}')\n",
    "        CROSS JOIN thresholds\n",
    "        GROUP BY threshold\n",
    "        ORDER BY threshold\n",
    "    \"\"\").df()\n",
    "\n",
    "    timing_windows = con.execute(f\"\"\"\n",
    "        SELECT\n",
    "            AVG(n_blocks_0_1d) AS avg_blocks_0_1d,\n",
    "            AVG(n_blocks_1_3d) AS avg_blocks_1_3d,\n",
    "            AVG(n_blocks_3_7d) AS avg_blocks_3_7d,\n",
    "            AVG(n_blocks_7_10d) AS avg_blocks_7_10d,\n",
    "\n",
    "            AVG((n_blocks_0_1d > 0)::INTEGER) AS share_with_blocks_0_1d,\n",
    "            AVG((n_blocks_1_3d > 0)::INTEGER) AS share_with_blocks_1_3d,\n",
    "            AVG((n_blocks_3_7d > 0)::INTEGER) AS share_with_blocks_3_7d,\n",
    "            AVG((n_blocks_7_10d > 0)::INTEGER) AS share_with_blocks_7_10d\n",
    "        FROM read_parquet('{path}')\n",
    "    \"\"\").df()\n",
    "\n",
    "    daily = con.execute(f\"\"\"\n",
    "        SELECT\n",
    "            day,\n",
    "            avg_blocks_received_day,\n",
    "            share_with_blocks_day,\n",
    "            max_blocks_received_day\n",
    "        FROM (\n",
    "            SELECT 0 AS day, AVG(n_blocks_day_0) AS avg_blocks_received_day, AVG(has_block_day_0) AS share_with_blocks_day, MAX(n_blocks_day_0) AS max_blocks_received_day FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 1 AS day, AVG(n_blocks_day_1), AVG(has_block_day_1), MAX(n_blocks_day_1) FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 2 AS day, AVG(n_blocks_day_2), AVG(has_block_day_2), MAX(n_blocks_day_2) FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 3 AS day, AVG(n_blocks_day_3), AVG(has_block_day_3), MAX(n_blocks_day_3) FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 4 AS day, AVG(n_blocks_day_4), AVG(has_block_day_4), MAX(n_blocks_day_4) FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 5 AS day, AVG(n_blocks_day_5), AVG(has_block_day_5), MAX(n_blocks_day_5) FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 6 AS day, AVG(n_blocks_day_6), AVG(has_block_day_6), MAX(n_blocks_day_6) FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 7 AS day, AVG(n_blocks_day_7), AVG(has_block_day_7), MAX(n_blocks_day_7) FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 8 AS day, AVG(n_blocks_day_8), AVG(has_block_day_8), MAX(n_blocks_day_8) FROM read_parquet('{path}')\n",
    "            UNION ALL\n",
    "            SELECT 9 AS day, AVG(n_blocks_day_9), AVG(has_block_day_9), MAX(n_blocks_day_9) FROM read_parquet('{path}')\n",
    "        )\n",
    "        ORDER BY day\n",
    "    \"\"\").df()\n",
    "\n",
    "    with open(out_txt, \"w\", encoding=\"utf-8\") as f:\n",
    "        f.write(f\"BLOCKS SUMMARY - {label.upper()}\\n\")\n",
    "        f.write(\"=\" * 80 + \"\\n\\n\")\n",
    "\n",
    "        f.write(\"Input file:\\n\")\n",
    "        f.write(str(path) + \"\\n\\n\")\n",
    "\n",
    "        f.write(\"GENERAL SUMMARY\\n\")\n",
    "        f.write(\"-\" * 80 + \"\\n\")\n",
    "        f.write(general.to_string(index=False))\n",
    "        f.write(\"\\n\\n\")\n",
    "\n",
    "        f.write(\"THRESHOLD SHARES\\n\")\n",
    "        f.write(\"-\" * 80 + \"\\n\")\n",
    "        f.write(thresholds.to_string(index=False))\n",
    "        f.write(\"\\n\\n\")\n",
    "\n",
    "        f.write(\"TIMING WINDOWS\\n\")\n",
    "        f.write(\"-\" * 80 + \"\\n\")\n",
    "        f.write(timing_windows.to_string(index=False))\n",
    "        f.write(\"\\n\\n\")\n",
    "\n",
    "        f.write(\"DAILY SUMMARY FOR PLOTS\\n\")\n",
    "        f.write(\"-\" * 80 + \"\\n\")\n",
    "        f.write(\"day = 0 means last day before event_time; day = 9 means 9-10 days before event_time.\\n\\n\")\n",
    "        f.write(daily.to_string(index=False))\n",
    "        f.write(\"\\n\")\n",
    "\n",
    "    print(f\"Wrote: {out_txt}\")\n",
    "\n",
    "\n",
    "write_text_summary(POS_OUT, POS_SUMMARY_TXT, \"positives\")\n",
    "write_text_summary(NEG_OUT, NEG_SUMMARY_TXT, \"negatives\")\n",
    "\n",
    "\n",
    "# =========================\n",
    "# COMPARISON PRINT ONLY\n",
    "# =========================\n",
    "\n",
    "print(\"\\n=== TARGET COMPARISON PRINT ONLY ===\")\n",
    "\n",
    "comparison = con.execute(f\"\"\"\n",
    "WITH all_data AS (\n",
    "    SELECT * FROM read_parquet('{POS_OUT}')\n",
    "    UNION ALL\n",
    "    SELECT * FROM read_parquet('{NEG_OUT}')\n",
    ")\n",
    "SELECT\n",
    "    target,\n",
    "    COUNT(*) AS n_obs,\n",
    "    COUNT(DISTINCT did) AS n_dids,\n",
    "    AVG(has_block_10d) AS share_with_blocks,\n",
    "    AVG(n_blocks_received_10d) AS avg_blocks,\n",
    "    MEDIAN(n_blocks_received_10d) AS median_blocks,\n",
    "    QUANTILE_CONT(n_blocks_received_10d, 0.95) AS p95_blocks,\n",
    "    MAX(n_blocks_received_10d) AS max_blocks\n",
    "FROM all_data\n",
    "GROUP BY target\n",
    "ORDER BY target\n",
    "\"\"\").df()\n",
    "\n",
    "print(comparison.to_string(index=False))\n",
    "\n",
    "\n",
    "print(\"\\n=== OUTPUT FILES ===\")\n",
    "for p in [\n",
    "    POS_OUT,\n",
    "    NEG_OUT,\n",
    "    POS_SUMMARY_TXT,\n",
    "    NEG_SUMMARY_TXT,\n",
    "]:\n",
    "    print(p)\n",
    "\n",
    "con.close()\n",
